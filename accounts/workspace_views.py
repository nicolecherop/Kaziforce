"""Explicit workspace switching, private notifications and email preferences."""

from django import forms
from django.contrib import messages
from django.contrib.auth.decorators import login_required
from django.core.paginator import Paginator
from django.shortcuts import get_object_or_404, redirect, render
from django.utils import timezone
from django.views.decorators.cache import never_cache
from django.views.decorators.http import require_GET, require_POST, require_http_methods

from .models import Notification
from .workspaces import select_workspace


@login_required
@never_cache
@require_POST
def switch_workspace(request):
    select_workspace(request, request.POST.get("workspace"), enable=True)
    messages.success(
        request, f"You are now in your {request.user.active_workspace} workspace."
    )
    return redirect("accounts:dashboard")


@login_required
@never_cache
@require_GET
def notifications(request):
    rows = Notification.objects.filter(recipient=request.user)
    return render(
        request,
        "accounts/notifications.html",
        {"page": Paginator(rows, 20).get_page(request.GET.get("page"))},
    )


@login_required
@never_cache
@require_POST
def open_notification(request, pk):
    item = get_object_or_404(Notification, pk=pk, recipient=request.user)
    select_workspace(request, item.workspace)
    if item.read_at is None:
        item.read_at = timezone.now()
        item.save(update_fields=["read_at"])
    # Paths are generated by server-side events, never copied from a POST.
    if not item.path.startswith("/") or item.path.startswith("//") or "\\" in item.path:
        return redirect("accounts:notifications")
    return redirect(item.path)


class NotificationPreferencesForm(forms.Form):
    email_updates = forms.BooleanField(
        label="Email me application and booking updates", required=False
    )


@login_required
@never_cache
@require_http_methods(["GET", "POST"])
def notification_settings(request):
    form = NotificationPreferencesForm(
        request.POST if request.method == "POST" else None,
        initial={"email_updates": request.user.email_updates},
    )
    if request.method == "POST" and form.is_valid():
        request.user.email_updates = form.cleaned_data["email_updates"]
        request.user.save(update_fields=["email_updates"])
        messages.success(request, "Your notification settings have been saved.")
        return redirect("accounts:notification_settings")
    return render(request, "accounts/notification_settings.html", {"form": form})
